#!/usr/bin/env python3
"""
run_experiments.py — reproduces every experiment reported in the paper
(Table "Summary of Experimental Results") through the full VBE gate
(transpile -> ESBMC -> signed JSON-LD evidence).

Outputs:
  results/experiments.csv   machine-readable results
  results/experiments.md    human-readable table
  results/evidence/*.jsonld signed evidence records (one per run)
  results/logs/*.log        raw ESBMC output (one per run)

Usage: python3 scripts/run_experiments.py
"""

import csv
import pathlib
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "governance"))

import vbe_gate  # noqa: E402

# (exp id, circuit file, encoding override, expected verdict)
EXPERIMENTS = [
    ("1",  "qsharp/TestXXIdentity.qs",   None,    "UNSAT"),
    ("2a", "qsharp/TestHHIdentity.qs",   None,    "UNSAT"),
    ("2b", "qsharp/TestCNOTIdentity.qs", None,    "UNSAT"),
    ("3",  "qsharp/TestBellState.qs",    None,    "UNSAT"),
    ("4",  "qsharp/TestSIdentity.qs",    None,    "SAT"),
    ("5",  "qsharp/TestQRNG.qs",         None,    "UNSAT"),
    ("6a", "qsharp/TestTGate.qs",        None,    "UNSAT"),
    ("6b", "qsharp/TestTGate.qs",        "exact", "UNSAT"),
]

CIRCUIT_LABELS = {
    "1":  "X.X",
    "2a": "H.H",
    "2b": "CNOT.CNOT",
    "3":  "Bell state",
    "4":  "S.S != I (fault)",
    "5":  "QRNG (H)",
    "6a": "H.T.T = H.S",
    "6b": "H.T.T = H.S",
}


def main():
    results_dir = REPO_ROOT / "results"
    logs_dir = results_dir / "logs"
    logs_dir.mkdir(parents=True, exist_ok=True)

    rows = []
    failures = 0
    for exp_id, circuit, encoding, expected in EXPERIMENTS:
        record, _ = vbe_gate.run_gate(
            str(REPO_ROOT / circuit),
            encoding=encoding,
            out_dir=str(results_dir / "evidence"),
            build_dir=str(REPO_ROOT / "build"),
            quiet=True,
        )
        metrics, info = record["_metrics"], record["_info"]

        log_name = f"{pathlib.Path(circuit).stem}{'_' + encoding if encoding else ''}.log"
        (logs_dir / log_name).write_text(metrics["raw_output"])

        ok = metrics["verdict"] == expected
        if not ok:
            failures += 1
        status = "as expected" if ok else f"UNEXPECTED (wanted {expected})"
        print(f"Exp {exp_id:<3} {CIRCUIT_LABELS[exp_id]:<18} "
              f"[{info['encoding']:<5}] -> {metrics['verdict']:<7} "
              f"solver={metrics.get('solver_time_s', '?')}s "
              f"wall={metrics['wall_time_s']}s  ({status})")

        rows.append({
            "exp": exp_id,
            "circuit": CIRCUIT_LABELS[exp_id],
            "property": info["property"],
            "encoding": info["encoding"],
            "qubits": info["qubits"],
            "depth": info["depth"],
            "bound_k": info["bound_k"],
            "vccs": metrics.get("vccs_generated"),
            "verdict": metrics["verdict"],
            "solver_time_s": metrics.get("solver_time_s"),
            "bmc_time_s": metrics.get("bmc_time_s"),
            "wall_time_s": metrics["wall_time_s"],
            "governance_decision": record["governance_decision"],
        })

    csv_path = results_dir / "experiments.csv"
    with open(csv_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)

    md_path = results_dir / "experiments.md"
    with open(md_path, "w") as f:
        f.write("# Experimental results (generated by scripts/run_experiments.py)\n\n")
        f.write("| Exp | Circuit | Property | Encoding | k | VCCs | Verdict "
                "| Solver (s) | Total (s) | Decision |\n")
        f.write("|-----|---------|----------|----------|---|------|---------"
                "|-----------|-----------|----------|\n")
        for r in rows:
            f.write(f"| {r['exp']} | {r['circuit']} | {r['property']} "
                    f"| {r['encoding']} | {r['bound_k']} | {r['vccs']} "
                    f"| {r['verdict']} | {r['solver_time_s']} "
                    f"| {r['wall_time_s']} | {r['governance_decision']} |\n")

    print(f"\n[ok] results: {csv_path}, {md_path}")
    if failures:
        print(f"[FAIL] {failures} experiment(s) returned unexpected verdicts")
        sys.exit(1)
    print("[ok] all verdicts as expected")


if __name__ == "__main__":
    main()
