#!/usr/bin/env python3
"""
run_benchmark.py — scalability benchmark for the ESBMC-Q# VBE pipeline.

Generates straight-line C harnesses for GHZ-n preparation circuits
(H on q0 followed by a CNOT chain), with increasing qubit counts n and two
values of the bound k per n, and measures where SMT solving starts to
struggle. Four verification regimes are exercised, in increasing order of
symbolic generality:

  func   concrete initial state |0..0>; assert the target GHZ amplitudes
         (functional correctness, k = n gates). Constant inputs: this is
         the regime comparable to what a single simulator run could check.
  basis  symbolic basis state |idx> with nondeterministic idx < 2^n; apply
         GHZ then its inverse and assert component-wise equality with the
         initial state (k = 2n gates). One verification covers ALL 2^n
         basis inputs simultaneously - already beyond a single simulation.
  unit   fully symbolic initial state (nondet amplitudes constrained to
         unit norm); assert norm preservation after the circuit
         (numerical stability / unitarity for ALL input states, k = n).
  ident  fully symbolic initial state; apply GHZ then its inverse and
         assert component-wise equality with the initial state (k = 2n).

The state vector uses the IEEE 754 encoding (--floatbv), matching the
paper's experiments. Qubit 0 is the most significant bit of the index.

For each regime the sweep stops at the first TIMEOUT (larger instances are
assumed to time out as well; this is recorded explicitly). The fully
symbolic regimes include n = 1 to locate the wall precisely.

Outputs: results/benchmark.csv, results/benchmark.md, build/benchmarks/*.c

Usage: python3 scripts/run_benchmark.py [--timeout 300] [--max-qubits 14]
"""

import argparse
import csv
import math
import os
import pathlib
import re
import subprocess
import sys
import time

REPO_ROOT = pathlib.Path(__file__).resolve().parents[1]
ESBMC_BIN = os.environ.get("ESBMC", "esbmc")
ESBMC_FLAGS = ["--unwind", "1", "--z3", "--floatbv"]

INV_SQRT2 = "0.70710678118654752440"

RE_SOLVER_TIME = re.compile(r"Runtime decision procedure: ([\d.]+)s")
RE_VCCS = re.compile(r"Generated (\d+) VCC\(s\), (\d+) remaining")


def emit_gate(lines, gate, n, src, dst):
    """Emit one gate as straight-line assignments from buffer src to dst."""
    dim = 1 << n
    if gate[0] == "H":  # Hadamard on qubit 0 (MSB)
        half = dim >> 1
        for i in range(half):
            j = i | half
            lines.append(f"    {dst}r[{i}] = INV_SQRT2 * ({src}r[{i}] + {src}r[{j}]);")
            lines.append(f"    {dst}i[{i}] = INV_SQRT2 * ({src}i[{i}] + {src}i[{j}]);")
            lines.append(f"    {dst}r[{j}] = INV_SQRT2 * ({src}r[{i}] - {src}r[{j}]);")
            lines.append(f"    {dst}i[{j}] = INV_SQRT2 * ({src}i[{i}] - {src}i[{j}]);")
    else:  # ("CNOT", control, target)
        _, c, t = gate
        cbit = 1 << (n - 1 - c)
        tbit = 1 << (n - 1 - t)
        for m in range(dim):
            srcidx = (m ^ tbit) if (m & cbit) else m
            lines.append(f"    {dst}r[{m}] = {src}r[{srcidx}];")
            lines.append(f"    {dst}i[{m}] = {src}i[{srcidx}];")


def emit_norm(lines, var, buf, dim):
    """Accumulate the squared norm with linear statements (a single huge
    expression tree overflows the model checker's recursive converter)."""
    lines.append(f"    double {var} = 0.0;")
    for i in range(dim):
        lines.append(f"    {var} += {buf}r[{i}]*{buf}r[{i}] + {buf}i[{i}]*{buf}i[{i}];")


def emit_chunked_assert(lines, conds, message, chunk=32):
    """Emit a conjunction as several smaller asserts (bounded nesting depth)."""
    for start in range(0, len(conds), chunk):
        group = conds[start:start + chunk]
        lines.append(f"    __ESBMC_assert({' && '.join(group)},")
        lines.append(f"                   \"{message}\");")


def generate(n, variant):
    """Generate the C harness for GHZ-n under the given regime."""
    dim = 1 << n
    gates = [("H",)] + [("CNOT", q, q + 1) for q in range(n - 1)]
    if variant in ("basis", "ident"):
        gates += [("CNOT", q, q + 1) for q in reversed(range(n - 1))] + [("H",)]
    depth = len(gates)

    lines = [
        f"/* GHZ-{n} scalability benchmark, regime '{variant}', k = {depth} gates.",
        f" * Generated by scripts/run_benchmark.py — do not edit by hand. */",
        f"#define INV_SQRT2 {INV_SQRT2}",
        f"#define DIM {dim}",
        "",
    ]
    if variant in ("unit", "ident"):
        lines.append("extern double __VERIFIER_nondet_double(void);")
        lines.append("")
    elif variant == "basis":
        lines.append("extern unsigned int __VERIFIER_nondet_uint(void);")
        lines.append("")
    lines.append("int main() {")

    # Buffer declarations: ping-pong between a and b on each gate.
    for b in "ab":
        lines.append(f"    double {b}r[DIM]; double {b}i[DIM];")

    if variant == "func":
        lines.append("    /* Concrete initial state |0...0>. */")
        lines.append("    ar[0] = 1.0; ai[0] = 0.0;")
        for i in range(1, dim):
            lines.append(f"    ar[{i}] = 0.0; ai[{i}] = 0.0;")
    elif variant == "basis":
        lines.append("    /* Symbolic basis state |idx>: one verification covers all")
        lines.append("     * 2^n computational-basis inputs simultaneously. */")
        lines.append("    unsigned int idx = __VERIFIER_nondet_uint();")
        lines.append(f"    __ESBMC_assume(idx < {dim}u);")
        for i in range(dim):
            lines.append(f"    ar[{i}] = (idx == {i}u) ? 1.0 : 0.0; ai[{i}] = 0.0;")
    else:
        lines.append("    /* Fully symbolic initial state, constrained to unit norm")
        lines.append("     * (assume band slightly tighter than the assert band so that")
        lines.append("     * IEEE 754 rounding cannot produce spurious counterexamples). */")
        for i in range(dim):
            lines.append(f"    ar[{i}] = __VERIFIER_nondet_double();")
            lines.append(f"    ai[{i}] = __VERIFIER_nondet_double();")
            lines.append(f"    __ESBMC_assume(ar[{i}] >= -1.001 && ar[{i}] <= 1.001);")
            lines.append(f"    __ESBMC_assume(ai[{i}] >= -1.001 && ai[{i}] <= 1.001);")
        emit_norm(lines, "norm_in", "a", dim)
        lines.append("    __ESBMC_assume(norm_in >= 0.9995 && norm_in <= 1.0005);")

    bufs = "ab"
    cur = 0
    for g in gates:
        lines.append("")
        label = g[0] if g[0] == "H" else f"CNOT(q{g[1]},q{g[2]})"
        lines.append(f"    /* gate: {label} */")
        emit_gate(lines, g, n, bufs[cur], bufs[1 - cur])
        cur = 1 - cur
    out = bufs[cur]

    lines.append("")
    if variant == "func":
        lines.append("    /* Target GHZ amplitudes: (|0..0> + |1..1>)/sqrt(2). */")
        conds = [f"{out}r[0] >= INV_SQRT2 - 0.001 && {out}r[0] <= INV_SQRT2 + 0.001",
                 f"{out}r[{dim-1}] >= INV_SQRT2 - 0.001 && {out}r[{dim-1}] <= INV_SQRT2 + 0.001"]
        for i in range(dim):
            conds.append(f"{out}i[{i}] >= -0.001 && {out}i[{i}] <= 0.001")
            if i not in (0, dim - 1):
                conds.append(f"{out}r[{i}] >= -0.001 && {out}r[{i}] <= 0.001")
        emit_chunked_assert(lines, conds, f"GHZ-{n} amplitudes diverge from target")
    elif variant == "unit":
        emit_norm(lines, "norm_out", out, dim)
        lines.append("    __ESBMC_assert(norm_out >= 0.999 && norm_out <= 1.001,")
        lines.append(f"                   \"GHZ-{n}: norm not preserved\");")
    else:  # basis / ident: functional equivalence with the initial state
        conds = []
        for i in range(dim):
            conds.append(f"{out}r[{i}] >= ar[{i}] - 0.001 && {out}r[{i}] <= ar[{i}] + 0.001")
            conds.append(f"{out}i[{i}] >= ai[{i}] - 0.001 && {out}i[{i}] <= ai[{i}] + 0.001")
        emit_chunked_assert(lines, conds, f"GHZ-{n}.inverse != identity")

    lines.append("    return 0;")
    lines.append("}")
    return "\n".join(lines), depth


def run_one(c_path, timeout):
    cmd = [ESBMC_BIN, str(c_path)] + ESBMC_FLAGS
    started = time.monotonic()
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True,
                              timeout=timeout)
        wall = time.monotonic() - started
        out = proc.stdout + proc.stderr
        if "VERIFICATION SUCCESSFUL" in out:
            verdict = "UNSAT"
        elif "VERIFICATION FAILED" in out:
            verdict = "SAT"
        else:
            verdict = "ERROR"
    except subprocess.TimeoutExpired:
        return {"verdict": "TIMEOUT", "wall": timeout, "solver": None, "vccs": None}
    solver = float(m.group(1)) if (m := RE_SOLVER_TIME.search(out)) else None
    vccs = remaining = None
    if m := RE_VCCS.search(out):
        vccs, remaining = int(m.group(1)), int(m.group(2))
    if solver is None and remaining == 0:
        # All VCCs discharged by constant propagation: no solver call needed.
        solver = 0.0
    return {"verdict": verdict, "wall": wall, "solver": solver, "vccs": vccs}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--timeout", type=float, default=300.0,
                    help="per-run timeout in seconds (default 300)")
    ap.add_argument("--max-qubits", type=int, default=14)
    args = ap.parse_args()

    bench_dir = REPO_ROOT / "build" / "benchmarks"
    bench_dir.mkdir(parents=True, exist_ok=True)
    results_dir = REPO_ROOT / "results"
    results_dir.mkdir(exist_ok=True)

    even_grid = list(range(2, args.max_qubits + 1, 2))
    # Fully symbolic regimes include n = 1 to locate the wall precisely.
    grids = {
        "func": even_grid,
        "basis": even_grid,
        "unit": [1] + even_grid,
        "ident": [1] + even_grid,
    }
    rows = []
    print(f"{'regime':<7} {'n':>3} {'states':>7} {'k':>4} {'verdict':<8} "
          f"{'solver(s)':>10} {'wall(s)':>9}", flush=True)
    print("-" * 56, flush=True)

    for variant in ("func", "basis", "unit", "ident"):
        for n in grids[variant]:
            code, depth = generate(n, variant)
            c_path = bench_dir / f"ghz_{variant}_{n:02d}q.c"
            c_path.write_text(code)

            r = run_one(c_path, args.timeout)
            rows.append({
                "regime": variant, "qubits": n, "states": 1 << n,
                "gates_k": depth, "verdict": r["verdict"],
                "vccs": r["vccs"],
                "solver_time_s": round(r["solver"], 3) if r["solver"] is not None else None,
                "wall_time_s": round(r["wall"], 3),
            })
            print(f"{variant:<7} {n:>3} {1 << n:>7} {depth:>4} {r['verdict']:<8} "
                  f"{r['solver'] if r['solver'] is not None else '-':>10} "
                  f"{r['wall']:>9.2f}", flush=True)
            if r["verdict"] == "TIMEOUT":
                print(f"{variant:<7} sweep stopped: first timeout at n = {n}",
                      flush=True)
                break

    csv_path = results_dir / "benchmark.csv"
    with open(csv_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    md_path = results_dir / "benchmark.md"
    with open(md_path, "w") as f:
        f.write("# Scalability benchmark (generated by scripts/run_benchmark.py)\n\n")
        f.write(f"Timeout per run: {args.timeout}s. Sweeps stop at the first "
                "timeout; larger instances are assumed to exceed the budget.\n\n")
        f.write("| Regime | n | States | k (gates) | VCCs | Verdict | Solver (s) | Wall (s) |\n")
        f.write("|--------|---|--------|-----------|------|---------|------------|----------|\n")
        for r in rows:
            f.write(f"| {r['regime']} | {r['qubits']} | {r['states']} "
                    f"| {r['gates_k']} | {r['vccs']} | {r['verdict']} "
                    f"| {r['solver_time_s']} | {r['wall_time_s']} |\n")

    print(f"\n[ok] results: {csv_path}, {md_path}")


if __name__ == "__main__":
    main()
